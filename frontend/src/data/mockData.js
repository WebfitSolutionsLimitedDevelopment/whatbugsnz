export const calcBugScore = (pain, market, gap, freq) => {
  const raw = pain * 0.35 + market * 0.25 + gap * 0.25 + freq * 0.15;
  return Math.round(raw * 10 * 10) / 10;
};

// Helper to build a bug record
const makeBug = (b) => ({
  ...b,
  bug_score: calcBugScore(
    b.pain_score,
    b.market_size_score,
    b.opportunity_gap_score,
    b.frequency_score,
  ),
});

